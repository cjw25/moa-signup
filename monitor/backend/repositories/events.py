from db import connect_db


def ensure_event_table(conn):
    """Keep old Compose volume rows while adopting the Day3 table name."""
    conn.execute("SELECT pg_advisory_xact_lock(5003001)")
    if conn.execute("SELECT to_regclass('public.http_events') AS name").fetchone()["name"] is not None:
        return
    if conn.execute("SELECT to_regclass('public.request_events') AS name").fetchone()["name"] is not None:
        conn.execute("ALTER TABLE request_events RENAME TO http_events")
        conn.execute("ALTER TABLE http_events ALTER COLUMN occurred_at SET DEFAULT CURRENT_TIMESTAMP")
    else:
        conn.execute("""
            CREATE TABLE http_events (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                method TEXT NOT NULL,
                path TEXT NOT NULL,
                status_code INTEGER NOT NULL,
                event_type TEXT NOT NULL DEFAULT 'http_request'
            )
        """)


def list_events(path="", status=None):
    clauses = []
    params = []
    if path:
        clauses.append("path ILIKE %s")
        params.append(f"%{path}%")
    if status is not None:
        clauses.append("status_code = %s")
        params.append(status)
    where = " WHERE " + " AND ".join(clauses) if clauses else ""
    with connect_db() as conn:
        ensure_event_table(conn)
        return conn.execute(
            "SELECT id, occurred_at, method, path, status_code, event_type FROM http_events"
            + where + " ORDER BY id DESC", params
        ).fetchall()


def create_event(method, path, status_code, event_type="http_request"):
    with connect_db() as conn:
        ensure_event_table(conn)
        return conn.execute(
            "INSERT INTO http_events (method, path, status_code, event_type) "
            "VALUES (%s, %s, %s, %s) RETURNING id, occurred_at",
            (method, path, status_code, event_type),
        ).fetchone()


def max_event_id():
    with connect_db() as conn:
        ensure_event_table(conn)
        return conn.execute("SELECT COALESCE(MAX(id), 0) AS id FROM http_events").fetchone()["id"]


def list_since(after_id, reference_time=None):
    with connect_db() as conn:
        ensure_event_table(conn)
        if reference_time is None:
            return conn.execute(
                "SELECT id, occurred_at, method, path, status_code, event_type "
                "FROM http_events WHERE id > %s ORDER BY id", (after_id,)
            ).fetchall()
        return conn.execute(
            "SELECT id, occurred_at, method, path, status_code, event_type "
            "FROM http_events WHERE id > %s AND occurred_at > %s::timestamptz - INTERVAL '60 seconds' "
            "AND occurred_at <= %s ORDER BY id", (after_id, reference_time, reference_time)
        ).fetchall()
