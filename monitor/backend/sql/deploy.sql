CREATE TABLE IF NOT EXISTS monitor_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL
);
DO $$ BEGIN
    IF to_regclass('public.http_events') IS NULL
       AND to_regclass('public.request_events') IS NOT NULL THEN
        ALTER TABLE request_events RENAME TO http_events;
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS http_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    status_code INTEGER NOT NULL,
    event_type TEXT NOT NULL DEFAULT 'http_request'
);
ALTER TABLE http_events ADD COLUMN IF NOT EXISTS event_type TEXT NOT NULL DEFAULT 'http_request';
ALTER TABLE http_events ALTER COLUMN occurred_at SET DEFAULT CURRENT_TIMESTAMP;
CREATE TABLE IF NOT EXISTS observation_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
